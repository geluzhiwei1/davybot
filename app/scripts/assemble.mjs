#!/usr/bin/env node
/**
 * assemble.mjs — 核心+业务域合树构建(拆库方案 §4.3 组装式构建)。
 *
 * 用法:
 *   node scripts/assemble.mjs [--mode server|production|...]   # 其余参数透传 vite build
 *   npm run build:full            # = assemble --mode production
 *   npm run build:server:full     # = assemble --mode server
 *
 * 流程(FAST FAIL):
 *   1. 清空并重建 .assemble/ = 整仓拷贝(排除 node_modules/dist/.git/.assemble)
 *      —— biz/ 一并拷入(manifest 需要)。
 *   2. 每个 biz/<domain>/ 合树(F7a 防漂移守卫:对核心源树判重,见 guardNoOverwrite):
 *        biz/<d>/routes/*      → .assemble/src/routes/
 *        biz/<d>/components/<c> → .assemble/src/components/<c>
 *        biz/<d>/lib/*          → .assemble/src/lib/
 *   3. 重写 .assemble/src/lib/biz-registry.ts ← 聚合各 manifest 的 sidebarGroups。
 *   4. symlink node_modules → 仓库根(依赖不重复安装)。
 *   5. 在 .assemble/ 内执行 `npx vite build <透传参数>`。
 *
 * 核心/开源构建不经本脚本(npm run build / build:server 直接 vite build,
 * biz/ 不在场 = 代码不存在)。
 */
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const APP = process.cwd();
const OUT = join(APP, ".assemble");
// biz 根:默认单仓形态(APP/biz);拆库后(拆库方案 §4.2)闭源业务域在独立仓,
// 经 DAVY_BIZ_ROOT 指向该仓的 biz/ 目录(相对路径按 APP 解析),如:
//   DAVY_BIZ_ROOT=../../davy-cloud/biz npm run build:server:full
const BIZ = process.env.DAVY_BIZ_ROOT ? resolve(process.env.DAVY_BIZ_ROOT) : join(APP, "biz");

const EXCLUDE = new Set(["node_modules", "dist", ".git", ".assemble", ".enterprise"]);

function copyApp() {
  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  for (const entry of readdirSync(APP, { withFileTypes: true })) {
    if (EXCLUDE.has(entry.name)) continue;
    cpSync(join(APP, entry.name), join(OUT, entry.name), {
      recursive: true,
      filter: (src) => !EXCLUDE.has(src.split("/").pop() ?? ""),
    });
  }
}

function listDomains() {
  if (!existsSync(BIZ)) return [];
  return readdirSync(BIZ, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(BIZ, d.name, "manifest.ts")))
    .map((d) => d.name);
}

// F7a(拆库方案 §5.2 组装防漂移):biz 只能"新增"文件,禁止覆盖核心树。
// 对核心源树(APP 下同路径)判重 + 跨 biz 域命名空间互斥;冲突 = 漂移,FAST FAIL。
// 唯一豁免:src/lib/biz-registry.ts 由 writeRegistry() 显式重写(组装接缝)。
const claimed = new Set();
function guardNoOverwrite(relPath, domain) {
  if (existsSync(join(APP, relPath))) {
    console.error(
      `[assemble] FATAL (F7a): biz/${domain} 试图覆盖核心文件 ${relPath} —— biz 只能新增文件,禁止改动核心树。`,
    );
    process.exit(1);
  }
  if (claimed.has(relPath)) {
    console.error(`[assemble] FATAL (F7a): biz/${domain} 与更早的 biz 域路径冲突 ${relPath} —— 各域命名空间必须互斥。`);
    process.exit(1);
  }
  claimed.add(relPath);
}

// lib 递归合树:允许 biz 向核心已有目录「新增」文件(部分目录共享,如
// src/lib/api/ —— api/index.ts 留核心,biz/normflow 补回 normflow.ts)。
// F7a 判重下沉到文件级:核心树同路径文件存在 / 跨域重复 = 漂移,FAST FAIL。
function mergeLibDeep(srcDir, relDir, domain) {
  for (const f of readdirSync(srcDir, { withFileTypes: true })) {
    const relPath = `${relDir}/${f.name}`;
    if (f.isDirectory()) {
      mergeLibDeep(join(srcDir, f.name), relPath, domain);
    } else {
      guardNoOverwrite(relPath, domain);
      mkdirSync(join(OUT, relDir), { recursive: true });
      cpSync(join(srcDir, f.name), join(OUT, relPath));
    }
  }
}

function mergeDomain(domain) {
  const root = join(BIZ, domain);
  const pairs = [
    [join(root, "routes"), "src/routes"],
    [join(root, "hooks"), "src/hooks"],
  ];
  for (const [src, rel] of pairs) {
    if (!existsSync(src)) continue;
    const dest = join(OUT, rel);
    mkdirSync(dest, { recursive: true });
    for (const f of readdirSync(src)) {
      guardNoOverwrite(`${rel}/${f}`, domain);
      cpSync(join(src, f), join(dest, f), { recursive: true });
    }
  }
  const libRoot = join(root, "lib");
  if (existsSync(libRoot)) mergeLibDeep(libRoot, "src/lib", domain);
  const compRoot = join(root, "components");
  if (existsSync(compRoot)) {
    for (const c of readdirSync(compRoot, { withFileTypes: true })) {
      guardNoOverwrite(`src/components/${c.name}`, domain);
      cpSync(join(compRoot, c.name), join(OUT, "src", "components", c.name), { recursive: true });
    }
  }
}

