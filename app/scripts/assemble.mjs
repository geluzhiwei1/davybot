function writeRegistry(domains) {
  const imports = [];
  const sidebarSpreads = [];
  const chatSpreads = [];
  const emptySpreads = [];
  const emptyCompSpreads = [];
  const sinkSpreads = [];
  const ctxSelSpreads = [];
  const resetSpreads = [];
  const countSpreads = [];
  const dockSpreads = [];
  for (const d of domains) {
    const src = readFileSync(join(BIZ, d, "manifest.ts"), "utf8");
    // 域名可含连字符(deep-research 等),别名须是合法 JS 标识符(路径保持原样)
    const id = d.replace(/[^A-Za-z0-9_]/g, "_");
    imports.push(`import { sidebarGroups as _${id} } from "../../biz/${d}/manifest";`);
    sidebarSpreads.push(`  ..._${id},`);
    if (/export\s+const\s+taskChatViews/.test(src)) {
      imports.push(`import { taskChatViews as _tcv_${id} } from "../../biz/${d}/manifest";`);
      chatSpreads.push(`  ..._tcv_${id},`);
    }
    if (/export\s+const\s+workspaceEmptyStates/.test(src)) {
      imports.push(`import { workspaceEmptyStates as _wes_${id} } from "../../biz/${d}/manifest";`);
      emptySpreads.push(`  ..._wes_${id},`);
    }
    if (/export\s+const\s+workspaceEmptyComponents/.test(src)) {
      imports.push(`import { workspaceEmptyComponents as _wec_${id} } from "../../biz/${d}/manifest";`);
      emptyCompSpreads.push(`  ..._wec_${id},`);
    }
    if (/export\s+const\s+agentStatusSinks/.test(src)) {
      imports.push(`import { agentStatusSinks as _sink_${id} } from "../../biz/${d}/manifest";`);
      sinkSpreads.push(`  ..._sink_${id},`);
    }
    if (/export\s+const\s+sidebarContextSelects/.test(src)) {
      imports.push(`import { sidebarContextSelects as _ctxs_${id} } from "../../biz/${d}/manifest";`);
      ctxSelSpreads.push(`  ..._ctxs_${id},`);
    }
    if (/export\s+const\s+identityResetHooks/.test(src)) {
      imports.push(`import { identityResetHooks as _irh_${id} } from "../../biz/${d}/manifest";`);
      resetSpreads.push(`  ..._irh_${id},`);
    }
    if (/export\s+const\s+sidebarCountHooks/.test(src)) {
      imports.push(`import { sidebarCountHooks as _sch_${id} } from "../../biz/${d}/manifest";`);
      countSpreads.push(`  ..._sch_${id},`);
    }
    if (/export\s+const\s+rootDocks/.test(src)) {
      imports.push(`import { rootDocks as _dock_${id} } from "../../biz/${d}/manifest";`);
      dockSpreads.push(`  ..._dock_${id},`);
    }
  }
  const content = REGISTRY_TEMPLATE.replace("__IMPORTS__", imports.join("\n"))
    .replace("__SIDEBAR_SPREADS__", sidebarSpreads.join("\n"))
    .replace("__CHAT_SPREADS__", chatSpreads.join("\n"))
    .replace("__EMPTY_SPREADS__", emptySpreads.join("\n"))
    .replace("__EMPTYCOMP_SPREADS__", emptyCompSpreads.join("\n"))
    .replace("__SINK_SPREADS__", sinkSpreads.join("\n"))
    .replace("__CTXSEL_SPREADS__", ctxSelSpreads.join("\n"))
    .replace("__RESET_SPREADS__", resetSpreads.join("\n"))
    .replace("__COUNT_SPREADS__", countSpreads.join("\n"))
    .replace("__DOCK_SPREADS__", dockSpreads.join("\n"));
  writeFileSync(join(OUT, "src", "lib", "biz-registry.ts"), content);
}

function main() {
  const domains = listDomains();
  if (domains.length === 0) {
    console.error("[assemble] FATAL: 未发现任何业务域(biz/<domain>/manifest.ts)。");
    console.error("[assemble]   单仓形态: app 根下应含 biz/;");
    console.error("[assemble]   拆库跨仓形态: 设置 DAVY_BIZ_ROOT 指向闭源仓 biz/ 目录(见 davy-cloud README);");
    console.error("[assemble]   仅核心构建请用 npm run build / build:server(不经本脚本)。");
    process.exit(1);
  }
  console.log(`[assemble] domains: ${domains.join(", ")}`);
  copyApp();
  // 跨仓形态(DAVY_BIZ_ROOT):APP 拷贝不含 biz → 把各域 manifest 落位
  // .assemble/biz/<d>/,供 writeRegistry 生成的相对导入(../../biz/<d>/manifest)
  // 解析。manifest 仅 import "../../src/..." 合树路径(§11.3),故单文件自洽;
  // 单仓形态下 copyApp 已整树拷入,此处为幂等重写。
  for (const d of domains) {
    mkdirSync(join(OUT, "biz", d), { recursive: true });
    cpSync(join(BIZ, d, "manifest.ts"), join(OUT, "biz", d, "manifest.ts"));
  }
  for (const d of domains) mergeDomain(d);
  writeRegistry(domains);
  symlinkSync(join(APP, "node_modules"), join(OUT, "node_modules"), "dir");

  const passThrough = process.argv.slice(2);
  const res = spawnSync("npx", ["vite", "build", ...passThrough], {
    cwd: OUT,
    stdio: "inherit",
  });
  if (res.status !== 0) {
    console.error(`[assemble] vite build failed (exit ${res.status})`);
    process.exit(res.status ?? 1);
  }
  console.log(`[assemble] done → ${join(OUT, "dist")}`);
}

main();
